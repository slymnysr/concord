/**
 * Mobil i18n.
 *
 * NEDEN VAR: mobil uygulamada i18n HİÇ YOKTU — 238 gömülü Türkçe string. Uygulama global;
 * mobil fiilen Türkçe-yalnız bir üründü.
 *
 * TASARIM: web'in (apps/web/src/i18n.ts) sözlük yapısı ve `t(key, params)` sözleşmesi
 * birebir yeniden kullanılır — iki farklı i18n API'si taşımak, aynı metnin iki yerde
 * ayrışmasına yol açar. Fark: locale kaynağı. Web'de kullanıcı seçer (localStorage);
 * mobilde CİHAZ DİLİ varsayılandır (kullanıcı telefonunu zaten ayarlamış).
 */
import AsyncStorage from '@react-native-async-storage/async-storage';
import { getLocales } from 'expo-localization';

export type Locale = 'tr' | 'en';
type Dict = Record<string, string>;

const STORAGE_KEY = 'concord_locale';

// Cihaz dili: 'tr-TR' → 'tr'. Desteklenmeyen dilde İngilizce (dünya genelinde en yaygın
// ikinci dil); Türkçe'ye düşmek global kullanıcıya anlamadığı bir arayüz göstermek olurdu.
function deviceLocale(): Locale {
  try {
    const tag = getLocales()[0]?.languageCode ?? 'en';
    return tag === 'tr' ? 'tr' : 'en';
  } catch {
    return 'en';
  }
}

let current: Locale = deviceLocale();

/** Kullanıcı tercihini yükle (varsa cihaz dilini ezer). App açılışında çağrılır. */
export async function loadLocale(): Promise<void> {
  try {
    const saved = await AsyncStorage.getItem(STORAGE_KEY);
    if (saved === 'tr' || saved === 'en') current = saved;
  } catch {
    // okunamadı → cihaz dili kalır
  }
}

export function getLocale(): Locale {
  return current;
}

export async function setLocale(l: Locale): Promise<void> {
  current = l;
  try {
    await AsyncStorage.setItem(STORAGE_KEY, l);
  } catch {
    // kalıcılaştırılamadı → bu oturumda yine de geçerli
  }
}

/** Intl API'lerine verilecek BCP-47 etiketi (tarih/sayı biçimlendirme). */
export function localeTag(): string {
  return current === 'en' ? 'en-US' : 'tr-TR';
}

export function t(key: string, params?: Record<string, string | number>): string {
  const d = current === 'en' ? en : tr;
  // Eksik anahtarda İngilizceye düş, sonra anahtarın kendisi (boş string göstermek,
  // sorunun sessizce kaybolması demek olurdu)
  let s = d[key] ?? en[key] ?? key;
  if (params) {
    for (const [k, v] of Object.entries(params)) s = s.replace(`{${k}}`, String(v));
  }
  return s;
}

/**
 * errText — API hatasını kullanıcının diline çevirir.
 * API `detail` alanı TÜRKÇEDİR ve gösterilmez (bkz. apps/api/docs/API-KONTRAT.md).
 */
export function errText(e: unknown, fallback?: string): string {
  const x = e as { status?: number; code?: string; detail?: string };
  if (x?.code) {
    if (x.detail) console.warn(`[api] ${x.code}: ${x.detail}`);
    const d = current === 'en' ? en : tr;
    if (d[`error.${x.code}`]) return t(`error.${x.code}`);
    switch (x.status) {
      case 400:
        return t('error.badRequest');
      case 401:
        return t('error.unauthorized');
      case 403:
        return t('error.forbidden');
      case 404:
        return t('error.notFound');
      case 429:
        return t('error.rateLimited');
      default:
        if ((x.status ?? 0) >= 500) return t('error.server');
    }
  }
  return fallback ?? t('error.generic');
}

