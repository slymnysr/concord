/**
 * Mobil i18n.
 *
 * NEDEN VAR: mobil uygulamada i18n HİÇ YOKTU — 238 gömülü Türkçe string. Uygulama global;
 * mobil fiilen Türkçe-yalnız bir üründü.
 *
 * TASARIM: web'in (apps/web/src/i18n.ts) sözlük yapısı ve `t(key, params)` sözleşmesi
 * birebir yeniden kullanılır — iki farklı i18n API'si taşımak, aynı metnin iki yerde
 * ayrışmasına yol açar. Fark: locale kaynağı. Web'de kullanıcı seçer (localStorage);
 * mobilde CİHAZ DİLİ varsayılandır (kullanıcı telefonunu zaten ayarlamış).
 */
import AsyncStorage from '@react-native-async-storage/async-storage';
import { getLocales } from 'expo-localization';

export type Locale = 'tr' | 'en' | 'de' | 'fr' | 'es' | 'pt' | 'ja';

const LOCALE_SET = new Set<string>(['tr', 'en', 'de', 'fr', 'es', 'pt', 'ja']);

/** Desteklenen dile normalize et; değilse null. 'pt-BR' → 'pt', 'DE' → 'de'. */
function normalize(tag: string | null | undefined): Locale | null {
  const base = (tag ?? '').toLowerCase().split(/[-_]/)[0];
  return LOCALE_SET.has(base) ? (base as Locale) : null;
}

const STORAGE_KEY = 'concord_locale';

// Cihaz dili: 'de-DE' → 'de', 'pt-BR' → 'pt'. Desteklenmeyen dilde İngilizce (dünya genelinde
// en yaygın ikinci dil); Türkçe'ye düşmek global kullanıcıya anlamadığı bir arayüz göstermek
// olurdu.
//
// DİKKAT: burası mobilde locale'in TEK kaynağıdır — dil seçici arayüzü YOKTUR (üstteki tasarım
// notu: kullanıcı telefonunu zaten ayarlamış). Bu yüzden `tag === 'tr' ? 'tr' : 'en'` demek,
// Almanca telefona İngilizce göstermek ve DE/FR/ES/PT/JA sözlüklerini ölü koda çevirmek demekti.
function deviceLocale(): Locale {
  try {
    return normalize(getLocales()[0]?.languageCode) ?? 'en';
  } catch {
    return 'en';
  }
}

let current: Locale = deviceLocale();

/** Kullanıcı tercihini yükle (varsa cihaz dilini ezer). App açılışında çağrılır. */
export async function loadLocale(): Promise<void> {
  try {
    const saved = normalize(await AsyncStorage.getItem(STORAGE_KEY));
    if (saved) current = saved;
  } catch {
    // okunamadı → cihaz dili kalır
  }
}

export function getLocale(): Locale {
  return current;
}

export async function setLocale(l: Locale): Promise<void> {
  current = l;
  try {
    await AsyncStorage.setItem(STORAGE_KEY, l);
  } catch {
    // kalıcılaştırılamadı → bu oturumda yine de geçerli
  }
}

// Intl etiketleri. Yalnızca dil kodu vermek (ör. 'ja') tarih/sayı biçimini bölgesiz bırakır;
// tam etiket doğru biçimi verir (ör. pt-BR'de 1.234,56 ve gg/aa/yyyy).
const INTL_TAGS: Record<Locale, string> = {
  tr: 'tr-TR',
  en: 'en-US',
  de: 'de-DE',
  fr: 'fr-FR',
  es: 'es-ES',
  pt: 'pt-BR',
  ja: 'ja-JP',
};

/** Intl API'lerine verilecek BCP-47 etiketi (tarih/sayı biçimlendirme). */
export function localeTag(): string {
  return INTL_TAGS[current];
}

/**
 * Sözlüğe DİNAMİK anahtarla bakış — t() derleme zamanı bilinmeyen anahtar alır
 * (errText: `error.${code}`), o yüzden key `keyof Dict`'e daraltılamaz.
 */
function look(d: Dict, k: string): string | undefined {
  return (d as Record<string, string | undefined>)[k];
}

export function t(key: string, params?: Record<string, string | number>): string {
  // `current === 'en' ? en : tr` idi: 'en' DIŞINDAKİ her dil (de/fr/es/pt/ja) Türkçe'ye
  // düşüyordu — sözlükleri dolu olmasına rağmen.
  const d = dicts[current];
  // Eksik anahtarda İngilizceye düş, sonra anahtarın kendisi (boş string göstermek,
  // sorunun sessizce kaybolması demek olurdu)
  let s = look(d, key) ?? look(en, key) ?? key;
  if (params) {
    for (const [k, v] of Object.entries(params)) s = s.replace(`{${k}}`, String(v));
  }
  return s;
}

/**
 * errText — API hatasını kullanıcının diline çevirir.
 * API `detail` alanı TÜRKÇEDİR ve gösterilmez (bkz. apps/api/docs/API-KONTRAT.md).
 */
export function errText(e: unknown, fallback?: string): string {
  const x = e as { status?: number; code?: string; detail?: string };
  if (x?.code) {
    if (x.detail) console.warn(`[api] ${x.code}: ${x.detail}`);
    if (look(dicts[current], `error.${x.code}`)) return t(`error.${x.code}`);
    switch (x.status) {
      case 400:
        return t('error.badRequest');
      case 401:
        return t('error.unauthorized');
      case 403:
        return t('error.forbidden');
      case 404:
        return t('error.notFound');
      case 429:
        return t('error.rateLimited');
      default:
        if ((x.status ?? 0) >= 500) return t('error.server');
    }
  }
  return fallback ?? t('error.generic');
}

